"""Aggregate running-task inventory for `task status` across sibling runtimes.

The per-repo status cannot see sibling keys generated by other parent
worktrees or repos, so admission (whether another lane may start) needs one
explicit aggregate scope over the current managed runtime tree. These tests
seed canonical result records in-process and observe real PIDs: no Git repos,
commits, spawns, or sleeps.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

import pytest

from scripts.cli import cmd_task as task_payload
from scripts.task_run import task_run, task_run_runtime

_LIVE_PID = os.getpid()


def _probe_dead(pid: int) -> bool:
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return True
    except PermissionError:
        return False
    return False


def _dead_pid() -> int:
    for pid in range(4_000_001, 4_000_101):
        if _probe_dead(pid):
            return pid
    raise AssertionError("no observably dead pid in probe range")


def _write_record(
    key: Path,
    task_id: str,
    payload: dict[str, object] | str,
    *,
    repo_root: str | None = None,
) -> Path:
    record = key / "task-run" / task_id
    record.mkdir(parents=True, exist_ok=True)
    result = record / "result.json"
    if isinstance(payload, str):
        result.write_text(payload, encoding="utf-8")
        return result
    body = dict(payload)
    body.setdefault("task_id", task_id)
    if repo_root is not None:
        body.setdefault("repo_root", repo_root)
    result.write_text(json.dumps(body), encoding="utf-8")
    return result


def _running(task_id: str, pid: int, **extra: object) -> dict[str, object]:
    return {"task_id": task_id, "status": "running", "phase": "exec", "runner_pid": pid, **extra}


def _keys(tmp_path: Path) -> tuple[Path, Path, Path]:
    keys_root = tmp_path / "cache" / "charness" / "runtime"
    key_a = keys_root / ("a" * 16)
    key_b = keys_root / ("b" * 16)
    (key_a / "task-run").mkdir(parents=True)
    (key_b / "task-run").mkdir(parents=True)
    return keys_root, key_a, key_b


def test_two_sibling_keys_with_non_s33_ids_count_together(tmp_path: Path) -> None:
    """The observed failure: two live lanes under two runtime namespaces, neither
    carrying the local lane-state prefix, must count together."""
    keys_root, key_a, key_b = _keys(tmp_path)
    before_a = _write_record(
        key_a,
        "goal870-owned-review-guard-finish-20261017",
        _running("goal870-owned-review-guard-finish-20261017", _LIVE_PID),
        repo_root="/repo/parent-a",
    )
    before_b = _write_record(
        key_b,
        "goal870-shared-types-claim-finish-20261017",
        _running(
            "goal870-shared-types-claim-finish-20261017",
            _LIVE_PID,
            scope=["module.py"],
            attempts=[{"n": n} for n in range(200)],
        ),
        repo_root="/repo/parent-b",
    )
    snapshot = {path: path.read_bytes() for path in (before_a, before_b)}

    payload = task_run_runtime.running_inventory_for_keys_root(keys_root)

    assert payload["event"] == "task-status-inventory"
    assert payload["scope"] == "managed-runtime-tree"
    assert payload["machine_global"] is False
    assert payload["running_count"] == 2
    assert payload["completeness"] == "complete"
    assert [task["task_id"] for task in payload["running_tasks"]] == [
        "goal870-owned-review-guard-finish-20261017",
        "goal870-shared-types-claim-finish-20261017",
    ]
    assert {task["runtime_root"] for task in payload["running_tasks"]} == {str(key_a), str(key_b)}
    # Bounded shape: identity/repo/runtime/phase/liveness only, never the record.
    for task in payload["running_tasks"]:
        assert set(task) == {
            "task_id",
            "repo_root",
            "runtime_root",
            "result_path",
            "status",
            "phase",
            "liveness",
            "inventory_state",
            "reason_code",
        }
        assert "attempts" not in task and "scope" not in task
        assert task["liveness"] == {"runner_pid": _LIVE_PID, "alive": True}
        assert task["reason_code"] is None
    # Read-only: observing changes no result bytes.
    assert {path: path.read_bytes() for path in snapshot} == snapshot


def test_live_terminal_stale_and_unknown_are_distinct(tmp_path: Path) -> None:
    keys_root, key_a, key_b = _keys(tmp_path)
    dead = _dead_pid()
    _write_record(key_a, "live-lane", _running("live-lane", _LIVE_PID))
    _write_record(
        key_a,
        "terminal-live-runner",
        {
            "task_id": "terminal-live-runner",
            "status": "completed",
            "phase": "terminal",
            "runner_pid": _LIVE_PID,
        },
    )
    _write_record(key_a, "stale-lane", _running("stale-lane", dead, phase="exec"))
    _write_record(
        key_b, "no-pid-lane", {"task_id": "no-pid-lane", "status": "running", "phase": "exec"}
    )
    _write_record(key_b, "malformed-lane", "{not json")
    _write_record(key_b, "list-lane", "[]\n")
    empty = key_b / "task-run" / "missing-lane"
    empty.mkdir(parents=True)
    as_dir = key_b / "task-run" / "dir-result"
    as_dir.mkdir(parents=True)
    (as_dir / "result.json").mkdir()

    payload = task_run_runtime.running_inventory_for_keys_root(keys_root)

    assert payload["running_count"] == 1
    assert [task["task_id"] for task in payload["running_tasks"]] == ["live-lane"]
    assert payload["terminal_count"] == 1
    assert [task["task_id"] for task in payload["stale_tasks"]] == ["stale-lane"]
    assert payload["stale_tasks"][0]["liveness"] == {"runner_pid": dead, "alive": False}
    by_id = {task["task_id"]: task for task in payload["unknown_tasks"]}
    assert set(by_id) == {
        "no-pid-lane",
        "malformed-lane",
        "list-lane",
        "missing-lane",
        "dir-result",
    }
    assert by_id["no-pid-lane"]["reason_code"] == task_run_runtime.UNKNOWN_RUNNER_UNCONFIRMED
    assert by_id["malformed-lane"]["reason_code"] == task_run_runtime.UNKNOWN_MALFORMED
    assert by_id["list-lane"]["reason_code"] == task_run_runtime.UNKNOWN_MALFORMED
    assert by_id["missing-lane"]["reason_code"] == task_run_runtime.UNKNOWN_RECORD_MISSING
    assert by_id["dir-result"]["reason_code"] == task_run_runtime.UNKNOWN_UNREADABLE
    # Unknown evidence forces partial completeness: never a silent zero-use claim.
    assert payload["unknown_count"] == 5
    assert payload["completeness"] == "partial"
    assert payload["completeness_reasons"] == [
        "5 task record(s) could not be classified; see unknown_tasks"
    ]


def test_nested_private_stores_are_not_double_counted(tmp_path: Path) -> None:
    """A key inside a key and a lane-private runtime are not task-run stores."""
    keys_root, key_a, _key_b = _keys(tmp_path)
    _write_record(key_a, "outer-lane", _running("outer-lane", _LIVE_PID))
    nested = key_a / "xdg-cache" / "charness" / "runtime" / ("c" * 16)
    _write_record(nested, "outer-lane", _running("outer-lane", _LIVE_PID))
    private = key_a / "task-run" / "outer-lane" / "runtime" / "task-run" / "outer-lane"
    private.mkdir(parents=True)
    (private / "result.json").write_text(
        json.dumps(_running("outer-lane", _LIVE_PID)), encoding="utf-8"
    )

    payload = task_run_runtime.running_inventory_for_keys_root(keys_root)

    assert payload["running_count"] == 1
    assert payload["scanned_keys"] == [key_a.name, _key_b.name]


def test_all_repos_rejects_a_task_id_without_touching_git() -> None:
    with pytest.raises(task_run.TaskRunError, match="--all-repos cannot be combined"):
        task_run_runtime.task_status(Path("/nonexistent"), "some-id", all_repos=True)


def test_explicit_standalone_root_states_its_limitation(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    explicit = tmp_path / "explicit"
    _write_record(explicit, "solo-lane", _running("solo-lane", _LIVE_PID))
    monkeypatch.setattr(task_run_runtime, "task_runtime_root", lambda _root: explicit)
    monkeypatch.setattr(
        task_run_runtime._git_owner, "_require_git_root", lambda root: Path(root).resolve()
    )

    payload = task_run_runtime.task_status(tmp_path, all_repos=True)

    assert payload["scope"] == "single-runtime-root"
    assert payload["keys_root"] is None
    assert payload["machine_global"] is False
    assert "no sibling keys" in payload["scope_limitation"]
    assert payload["running_count"] == 1
    assert payload["completeness"] == "complete"


def test_managed_wrapper_carries_repo_and_runtime(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    keys_root, key_a, key_b = _keys(tmp_path)
    _write_record(key_a, "lane-a", _running("lane-a", _LIVE_PID))
    _write_record(key_b, "lane-b", _running("lane-b", _LIVE_PID))
    monkeypatch.setattr(task_run_runtime, "task_runtime_root", lambda _root: key_a)
    monkeypatch.setattr(
        task_run_runtime._git_owner, "_require_git_root", lambda root: Path(root).resolve()
    )

    payload = task_run_runtime.task_status(tmp_path, all_repos=True)

    assert payload["keys_root"] == str(keys_root)
    assert payload["runtime_root"] == str(key_a)
    assert payload["repo_root"] == str(tmp_path.resolve())
    assert payload["running_count"] == 2


def test_ordinary_status_is_unchanged(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    keys_root, key_a, _key_b = _keys(tmp_path)
    record = {"task_id": "plain", "status": "completed", "phase": "terminal"}
    _write_record(key_a, "plain", record)
    monkeypatch.setattr(task_run_runtime, "task_runtime_root", lambda _root: key_a)
    monkeypatch.setattr(
        task_run_runtime._git_owner, "_require_git_root", lambda root: Path(root).resolve()
    )

    listing = task_run_runtime.task_status(tmp_path)
    single = task_run_runtime.task_status(tmp_path, "plain")

    assert listing["event"] == "task-status-list"
    assert [task["task_id"] for task in listing["tasks"]] == ["plain"]
    assert single["task_id"] == "plain"
    assert single["liveness"]["alive"] is None


def test_cmd_status_all_repos_emits_running_count(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """The one CLI boundary case: exact `cmd_task_status` output for a consumer."""
    keys_root, key_a, key_b = _keys(tmp_path)
    _write_record(key_a, "lane-a", _running("lane-a", _LIVE_PID))
    _write_record(key_b, "lane-b", _running("lane-b", _LIVE_PID))
    monkeypatch.setattr(task_payload, "_load_task_run_lib", lambda _args: task_run)
    monkeypatch.setattr(task_run_runtime, "task_runtime_root", lambda _root: key_a)
    monkeypatch.setattr(
        task_run_runtime._git_owner, "_require_git_root", lambda root: Path(root).resolve()
    )
    emitted: list[dict[str, object]] = []
    monkeypatch.setattr(task_payload, "emit_yaml", emitted.append)

    code = task_payload.cmd_task_status(
        argparse.Namespace(repo_root=tmp_path, task_id=None, all_repos=True)
    )

    assert code == 0
    assert emitted[-1]["event"] == "task-status-inventory"
    assert emitted[-1]["running_count"] == 2
    assert emitted[-1]["completeness"] == "complete"
    assert emitted[-1]["machine_global"] is False

    # Without the flag the same command keeps its per-repo shape.
    code = task_payload.cmd_task_status(argparse.Namespace(repo_root=tmp_path, task_id=None))

    assert code == 0
    assert emitted[-1]["event"] == "task-status-list"
    assert [task["task_id"] for task in emitted[-1]["tasks"]] == ["lane-a"]
