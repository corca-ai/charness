"""Aggregate running-task inventory for `task status` across sibling runtimes.

The per-repo status cannot see sibling keys generated by other parent
worktrees or repos, so admission (whether another lane may start) needs one
explicit aggregate scope over the current managed runtime tree. These tests
seed canonical result records in-process and observe real PIDs: no Git repos,
commits, spawns, or sleeps.
"""

from __future__ import annotations

import argparse
import json
import os
import runpy
import sys
from pathlib import Path

import pytest

from scripts.cli import cmd_task as task_payload
from scripts.task_run import task_run, task_run_runtime

_LIVE_PID = os.getpid()


def _write_record(
    key: Path,
    task_id: str,
    payload: dict[str, object] | str,
    *,
    repo_root: str | None = None,
) -> Path:
    record = key / "task-run" / task_id
    record.mkdir(parents=True, exist_ok=True)
    result = record / "result.json"
    if isinstance(payload, str):
        result.write_text(payload, encoding="utf-8")
        return result
    body = dict(payload)
    body.setdefault("task_id", task_id)
    if repo_root is not None:
        body.setdefault("repo_root", repo_root)
    result.write_text(json.dumps(body), encoding="utf-8")
    return result


def _running(task_id: str, pid: int, **extra: object) -> dict[str, object]:
    return {"task_id": task_id, "status": "running", "phase": "exec", "runner_pid": pid, **extra}


def _keys(tmp_path: Path) -> tuple[Path, Path, Path]:
    keys_root = tmp_path / "cache" / "charness" / "runtime"
    key_a = keys_root / ("a" * 16)
    key_b = keys_root / ("b" * 16)
    (key_a / "task-run").mkdir(parents=True)
    (key_b / "task-run").mkdir(parents=True)
    return keys_root, key_a, key_b


def test_two_sibling_keys_with_non_s33_ids_count_together(tmp_path: Path) -> None:
    """The observed failure: two live lanes under two runtime namespaces, neither
    carrying the local lane-state prefix, must count together."""
    keys_root, key_a, key_b = _keys(tmp_path)
    before_a = _write_record(
        key_a,
        "goal870-owned-review-guard-finish-20261017",
        _running("goal870-owned-review-guard-finish-20261017", _LIVE_PID),
        repo_root="/repo/parent-a",
    )
    before_b = _write_record(
        key_b,
        "goal870-shared-types-claim-finish-20261017",
        _running(
            "goal870-shared-types-claim-finish-20261017",
            _LIVE_PID,
            scope=["module.py"],
            attempts=[{"n": n} for n in range(200)],
        ),
        repo_root="/repo/parent-b",
    )
    snapshot = {path: path.read_bytes() for path in (before_a, before_b)}

    payload = task_run_runtime.running_inventory_for_keys_root(keys_root)

    assert payload["event"] == "task-status-inventory"
    assert payload["scope"] == "managed-runtime-tree"
    assert payload["machine_global"] is False
    assert payload["running_count"] == 2
    assert payload["completeness"] == "complete"
    assert [task["task_id"] for task in payload["running_tasks"]] == [
        "goal870-owned-review-guard-finish-20261017",
        "goal870-shared-types-claim-finish-20261017",
    ]
    assert {task["runtime_root"] for task in payload["running_tasks"]} == {str(key_a), str(key_b)}
    # Bounded shape: identity/repo/runtime/phase/liveness only, never the record.
    for task in payload["running_tasks"]:
        assert set(task) == {
            "task_id",
            "repo_root",
            "runtime_root",
            "result_path",
            "status",
            "phase",
            "liveness",
            "inventory_state",
            "reason_code",
        }
        assert "attempts" not in task and "scope" not in task
        assert task["liveness"] == {"runner_pid": _LIVE_PID, "alive": True}
        assert task["reason_code"] is None
    # Read-only: observing changes no result bytes.
    assert {path: path.read_bytes() for path in snapshot} == snapshot


def test_live_terminal_stale_and_unknown_are_distinct(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    keys_root, key_a, key_b = _keys(tmp_path)
    live_pid, dead_pid = 101, 202
    monkeypatch.setattr(
        task_run_runtime,
        "runner_liveness",
        lambda record: {
            "runner_pid": record.get("runner_pid"),
            "alive": (
                True
                if record.get("runner_pid") == live_pid
                else False if record.get("runner_pid") == dead_pid else None
            ),
        },
    )
    _write_record(key_a, "live-lane", _running("live-lane", live_pid))
    _write_record(
        key_a,
        "terminal-live-runner",
        {
            "task_id": "terminal-live-runner",
            "status": "completed",
            "phase": "terminal",
            "runner_pid": live_pid,
        },
    )
    for status in ("interrupted", "timed-out", "non-delivery"):
        _write_record(
            key_a,
            f"terminal-{status}",
            {"task_id": f"terminal-{status}", "status": status, "runner_pid": live_pid},
        )
    _write_record(key_a, "stale-lane", _running("stale-lane", dead_pid, phase="exec"))
    _write_record(
        key_b, "no-pid-lane", {"task_id": "no-pid-lane", "status": "running", "phase": "exec"}
    )
    _write_record(key_b, "malformed-lane", "{not json")
    _write_record(key_b, "list-lane", "[]\n")
    archive = key_b / "task-run" / ".failed-launch-archive"
    archive.mkdir()
    as_dir = key_b / "task-run" / "dir-result"
    as_dir.mkdir(parents=True)
    (as_dir / "result.json").mkdir()
    _write_record(
        key_b,
        "future-status",
        {"task_id": "future-status", "status": "unexpected-state", "runner_pid": live_pid},
    )

    payload = task_run_runtime.running_inventory_for_keys_root(keys_root)

    assert payload["running_count"] == 1
    assert [task["task_id"] for task in payload["running_tasks"]] == ["live-lane"]
    assert payload["terminal_count"] == 4
    assert payload["stale_count"] == 1
    assert payload["unknown_reasons"] == {
        task_run_runtime.UNKNOWN_MALFORMED: 2,
        task_run_runtime.UNKNOWN_RUNNER_UNCONFIRMED: 1,
        task_run_runtime.UNKNOWN_STATUS: 1,
        task_run_runtime.UNKNOWN_UNREADABLE: 1,
    }
    # The archive has no canonical result record, so it contributes no unknown.
    assert payload["unknown_count"] == 5
    assert payload["completeness"] == "partial"
    assert payload["completeness_reasons"] == [
        "5 task record(s) could not be classified; see unknown_reasons"
    ]


def test_result_disappearing_after_enumeration_stays_unknown(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    result = _write_record(
        tmp_path / "key", "vanished", _running("vanished", _LIVE_PID)
    )
    original = Path.read_text

    def disappear(path: Path, *args: object, **kwargs: object) -> str:
        if path == result:
            path.unlink()
        return original(path, *args, **kwargs)

    monkeypatch.setattr(Path, "read_text", disappear)

    entry = task_run_runtime.inventory_entry_for_result(result, tmp_path / "key")

    assert entry["inventory_state"] == "unknown"
    assert entry["reason_code"] == task_run_runtime.UNKNOWN_RECORD_MISSING


def test_unreadable_task_store_enumeration_makes_inventory_partial(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    keys_root, key_a, _key_b = _keys(tmp_path)
    _write_record(key_a, "hidden-lane", _running("hidden-lane", _LIVE_PID))
    store = key_a / "task-run"
    original_scandir = os.scandir

    def fail_store(path: int | os.PathLike[str] | str) -> os.ScandirIterator[str]:
        if not isinstance(path, int) and Path(path) == store:
            raise PermissionError("injected task-store read denial")
        return original_scandir(path)

    monkeypatch.setattr(os, "scandir", fail_store)

    payload = task_run_runtime.running_inventory_for_keys_root(keys_root)

    assert payload["running_count"] == 0
    assert payload["unknown_count"] == 0
    assert payload["completeness"] == "partial"
    assert len(payload["completeness_reasons"]) == 1
    assert "unreadable task-run store" in payload["completeness_reasons"][0]
    assert payload["unknown_reasons"] == {}


def test_non_directory_and_symlink_task_stores_make_inventory_partial(
    tmp_path: Path,
) -> None:
    keys_root, key_a, key_b = _keys(tmp_path)
    external_root = tmp_path / "external-key"
    _write_record(external_root, "outside-lane", _running("outside-lane", _LIVE_PID))

    non_directory_store = key_a / "task-run"
    non_directory_store.rmdir()
    non_directory_store.write_text("not a directory", encoding="utf-8")

    symlink_store = key_b / "task-run"
    symlink_store.rmdir()
    symlink_store.symlink_to(external_root / "task-run", target_is_directory=True)

    payload = task_run_runtime.running_inventory_for_keys_root(keys_root)

    assert payload["running_count"] == 0
    assert payload["completeness"] == "partial"
    assert len(payload["completeness_reasons"]) == 2
    assert all("task-run store" in reason for reason in payload["completeness_reasons"])


def test_nested_private_stores_are_not_double_counted(tmp_path: Path) -> None:
    """A key inside a key and a lane-private runtime are not task-run stores."""
    keys_root, key_a, _key_b = _keys(tmp_path)
    _write_record(key_a, "outer-lane", _running("outer-lane", _LIVE_PID))
    nested = key_a / "xdg-cache" / "charness" / "runtime" / ("c" * 16)
    _write_record(nested, "outer-lane", _running("outer-lane", _LIVE_PID))
    private = key_a / "task-run" / "outer-lane" / "runtime" / "task-run" / "outer-lane"
    private.mkdir(parents=True)
    (private / "result.json").write_text(
        json.dumps(_running("outer-lane", _LIVE_PID)), encoding="utf-8"
    )

    payload = task_run_runtime.running_inventory_for_keys_root(keys_root)

    assert payload["running_count"] == 1


